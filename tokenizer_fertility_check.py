# ── Metrics ────────────────────────────────────────────────────────────────────
def calculate_metrics(tokenizer, sentences):
    total_tokens = 0
    total_chars  = 0
    total_words  = 0

    for s in sentences:
        tokens       = tokenizer.encode(s, add_special_tokens=False)
        total_tokens += len(tokens)
        total_chars  += len(s)
        total_words  += len(s.split())          # whitespace word count

    return {
        "total_tokens":    total_tokens,
        "tokens_per_sent": total_tokens / len(sentences),   # original fertility
        "tokens_per_word": total_tokens / total_words,      # ASR fertility ← KEY
        "chars_per_token": total_chars  / total_tokens,     # compression
    }

